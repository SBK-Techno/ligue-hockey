async function renderSocialImage(
	root: string,
	branding: Branding,
	svg: Buffer,
	palette: EmailPalette
): Promise<Buffer> {
	const source = await readFile(path.join(root, branding.socialSource));
	const background = await sharp(source)
		.resize(SOCIAL_WIDTH, SOCIAL_HEIGHT, { fit: 'cover', position: 'centre' })
		.toBuffer();
	const crest = await sharp(svg)
		.resize(SOCIAL_CREST, SOCIAL_CREST)
		.png()
		.toBuffer();

	return sharp(background)
		.composite([
			{ input: buildSocialOverlay(palette), top: 0, left: 0 },
			{ input: crest, top: 64, left: 72 }
		])
		.jpeg({ quality: 88, mozjpeg: true })
		.toBuffer();
}

export async function generateBranding(root: string): Promise<GeneratedFile[]> {
	const raw = JSON.parse(
		await readFile(path.join(root, 'config/branding.json'), 'utf8')
	);
	const branding = brandingSchema.parse(raw);
	const appPalette = parsePalette(
		await readFile(path.join(root, 'src/lib/ui/tokens.css'), 'utf8')
	);
	const palette = emailPaletteFrom(appPalette);
	const svg = await readFile(path.join(root, branding.iconSource));

	const icons = {} as Record<IconRole, string>;
	const files: GeneratedFile[] = [];

	for (const { role, slug, sizeKey } of ICON_ROLES) {
		const size = branding.icons[sizeKey];
		const contents = await renderIcon(svg, branding, palette, size, role === 'maskable');
		const digest = sha256(contents).slice(0, 12);
		const publicPath = `/icons/${slug}-${size}.${digest}.png`;
		icons[role] = publicPath;
		files.push({ path: `static${publicPath}`, contents });
	}

	const manifest = buildManifest(branding, icons, palette);
	files.push({ path: `static${MANIFEST_PATH}`, contents: manifest });

	const criticalCss = await buildCriticalCss(root);
	files.push({ path: 'src/app.html', contents: buildAppShell(branding, palette, criticalCss) });
	files.push({
		path: 'src/lib/generated/critical-style.ts',
		contents: `${GENERATED_HEADER}export const CRITICAL_STYLE_HASH = '${criticalStyleHash(criticalCss)}';\n`
	});
	files.push({ path: `static${ROBOTS_PATH}`, contents: buildRobots(branding) });
	files.push({
		path: `static${OFFLINE_PATH}`,
		contents: buildOfflinePage(branding, appPalette)
	});

	const { files: authFiles, auth } = await renderAuthImages(root, branding);
	files.push(...authFiles);

	const textures = {} as Record<TextureKey, string>;
	for (const key of TEXTURE_KEYS) {
		const contents = await renderTexture(root, branding.textures[key], MATERIALS[key]);
		const publicPath = `/textures/${key}-${sha256(contents).slice(0, 12)}.webp`;
		textures[key] = publicPath;
		files.push({ path: `static${publicPath}`, contents });
	}

	const sheetContents = await buildIdentitySheet(root);
	if (sheetContents.length > PERFORMANCE_BUDGETS.identitySheetBytes) {
		throw new Error(
			`Planche d'identités trop lourde : ${sheetContents.length} octets pour un budget de ${PERFORMANCE_BUDGETS.identitySheetBytes}.`
		);
	}
	const identitySheet = `/identities/identities-${sha256(sheetContents).slice(0, 12)}.webp`;
	files.push({ path: `static${identitySheet}`, contents: sheetContents });

	const social = await renderSocialImage(root, branding, svg, palette);
	const socialImage = contentHashedPath(branding.socialImage, social);
	files.push({ path: `static${socialImage}`, contents: social });

	const moduleSource = buildBrandingModule(
		branding,
		icons,
		palette,
		auth,
		identitySheet,
		textures,
		socialImage
	);
	files.push({ path: 'src/lib/generated/branding.ts', contents: moduleSource });

	const checksums = {
		generatedBy: 'scripts/generate.ts',
		source: 'config/branding.json, config/i18n/fr.ts and src/lib/ui/tokens.css',
		files: Object.fromEntries(
			files.map((file) => [file.path, sha256(file.contents)])
		)
	};
	files.push({
		path: `static${GENERATED_ASSETS_PATH}`,
		contents: `${JSON.stringify(checksums, null, 2)}\n`
	});

	assertDeclaredSurfaces(files.map((file) => file.path));
	return files;
}

export async function writeGeneratedFiles(
	root: string,
	files: GeneratedFile[],
	nowMs: number = Date.now()
): Promise<void> {
	for (const file of files) {
		const target = path.join(root, file.path);
		await mkdir(path.dirname(target), { recursive: true });
		await writeFile(target, file.contents);
	}

	// Les icônes, la photo de connexion, la planche, les textures et l'image
	// sociale sont nommées par contenu. Une génération remplace le nom, donc
	// l'ancien reste servi pendant la fenêtre de cache des documents actifs;
	// au-delà, il est supprimé pour ne pas accumuler des octets morts.
	const expected = new Set(files.map((file) => file.path.split(path.sep).join('/')));
	for (const dir of [
		'static/icons',
		'static/auth',
		'static/textures',
		'static/identities',
		'static/social'
	]) {
		for (const name of await readdir(path.join(root, dir)).catch(() => [])) {
			const relative = `${dir}/${name}`;
			if (expected.has(relative)) continue;
			const target = path.join(root, dir, name);
			const info = await stat(target);
			if (retainedForCache(info.mtimeMs, nowMs)) continue;
			await unlink(target);
		}
	}
}

export function checksumOf(contents: Buffer | string): string {
	return sha256(contents);
}
