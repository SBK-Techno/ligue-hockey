const ICON_ROLES = [
	{ role: 'favicon', slug: 'favicon', sizeKey: 'favicon' },
	{ role: 'appleTouch', slug: 'apple-touch', sizeKey: 'appleTouch' },
	{ role: 'icon192', slug: 'icon-192', sizeKey: 'icon192' },
	{ role: 'icon512', slug: 'icon-512', sizeKey: 'icon512' },
	{ role: 'maskable', slug: 'maskable-512', sizeKey: 'maskable' }
] as const;

type IconRole = (typeof ICON_ROLES)[number]['role'];

function sha256(contents: Buffer | string): string {
	return createHash('sha256').update(contents).digest('hex');
}

async function renderIcon(
	svg: Buffer,
	branding: Branding,
	palette: EmailPalette,
	size: number,
	maskable: boolean
): Promise<Buffer> {
	if (maskable) {
		const innerSize = Math.round(size * branding.maskableScale);
		const inner = await sharp(svg).resize(innerSize, innerSize).png().toBuffer();
		return sharp({
			create: {
				width: size,
				height: size,
				channels: 4,
				background: palette.ink
			}
		})
			.composite([{ input: inner, gravity: 'center' }])
			.png({ compressionLevel: 9 })
			.toBuffer();
	}

	return sharp(svg)
		.resize(size, size)
		.flatten({ background: palette.ink })
		.png({ compressionLevel: 9 })
		.toBuffer();
}

