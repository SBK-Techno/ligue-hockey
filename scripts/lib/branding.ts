/**
 * La planche unique des portraits : une tuile carrée par identité, dans
 * l'ordre du catalogue. La source peinte est l'original; la planche livrée est
 * une seule image WebP nommée par son contenu. Un portrait manquant arrête la
 * génération au lieu de laisser un trou silencieux.
 */
export async function buildIdentitySheet(root: string): Promise<Buffer> {
	const { columns, tileSize, webpQuality, sourceDir, sourceExtension } = IDENTITY_SHEET;
	const rows = Math.ceil(IDENTITIES.length / columns);
	const composites: Array<{ input: Buffer; left: number; top: number }> = [];

	for (const [index, identity] of IDENTITIES.entries()) {
		const sourcePath = path.join(root, sourceDir, `${identity.id}${sourceExtension}`);
		let source: Buffer;
		try {
			source = await readFile(sourcePath);
		} catch {
			throw new Error(`Portrait manquant pour ${identity.id}: ${sourcePath}`);
		}
		const tile = await sharp(source)
			.resize(tileSize, tileSize, { fit: 'cover', position: 'centre' })
			.removeAlpha()
			.toBuffer();
		composites.push({
			input: tile,
			left: (index % columns) * tileSize,
			top: Math.floor(index / columns) * tileSize
		});
	}

	return sharp({
		create: {
			width: columns * tileSize,
			height: rows * tileSize,
			channels: 4,
			background: { r: 0, g: 0, b: 0, alpha: 0 }
		}
	})
		.composite(composites)
		.webp({ quality: webpQuality, effort: 6 })
		.toBuffer();
}

/** Le hash CSP de la tranche critique, calculé sur le texte exact injecté. */
export function criticalStyleHash(css: string): string {
	return `sha256-${createHash('sha256').update(css).digest('base64')}`;
}

/**
 * Le chemin public d'un actif nommé par son contenu. Le nom logique reste la
 * seule entrée de `config/branding.json`; le suffixe vient des octets.
 */
export function contentHashedPath(logicalPath: string, contents: Buffer | string): string {
	const extension = path.extname(logicalPath);
	const base = logicalPath.slice(0, -extension.length);
	return `${base}-${sha256(contents).slice(0, 12)}${extension}`;
}

function buildBrandingModule(
	branding: Branding,
	icons: Record<IconRole, string>,
	palette: EmailPalette,
	auth: AuthImages,
	identitySheet: string,
	textures: Record<TextureKey, string>,
	socialImage: string
) {
	const value = {
		name: branding.name,
		shortName: branding.shortName,
		organisation: branding.organisation,
		description: branding.description,
		locale: branding.locale,
		timezone: branding.timezone,
		startUrl: branding.startUrl,
		scope: branding.scope,
		display: branding.display,
		indexable: branding.indexable,
		themeColor: palette.ink,
		backgroundColor: palette.paper,
		emailPalette: palette,
		socialImage,
		auth,
		identitySheet,
		manifestPath: MANIFEST_PATH,
		offlinePath: OFFLINE_PATH,
		/**
		 * Tous les fichiers publics servis sans session : le manifeste, la page
		 * hors ligne, le robots, le service worker, le manifeste des actifs
		 * générés et les médias nommés par contenu. Un consommateur ne complète
		 * jamais cette liste lui-même.
		 */
		publicPaths: [
			...new Set([
				MANIFEST_PATH,
				OFFLINE_PATH,
				ROBOTS_PATH,
				SERVICE_WORKER_PATH,
				GENERATED_ASSETS_PATH,
				socialImage,
				...auth.srcset.split(', ').map((entry) => entry.split(' ')[0]),
				identitySheet,
				...Object.values(icons),
				...Object.values(textures)
			])
		],
		cachePrefix: cachePrefix(branding),
		icons,
		textures
	};

	return `${GENERATED_HEADER}export const branding = ${JSON.stringify(
		value,
		null,
		2
	)} as const;\n\nexport type Branding = typeof branding;\n`;
}

const SOCIAL_WIDTH = 1200;
const SOCIAL_HEIGHT = 630;
const SOCIAL_CREST = 184;
const AUTH_WIDTHS = [640, 960, 1200] as const;
const AUTH_RATIO = 2 / 3;

/**
 * Une matière couvre sa surface d'un seul tenant : la source est cadrée à la
 * taille native de la surface, puis compressée. Aucune répétition, aucune
 * couture, aucun motif en miroir.
 */
async function renderTexture(
	root: string,
	sourcePath: string,
	material: (typeof MATERIALS)[keyof typeof MATERIALS]
): Promise<Buffer> {
	const { width, height, quality, gamma, gain, budget } = material;
	const source = await readFile(path.join(root, sourcePath));
	const tile = await sharp(source)
		.resize(width, height, { fit: 'cover', position: 'centre' })
		.removeAlpha()
		.gamma(gamma)
		.linear(gain, 0)
		.webp({ quality, effort: 6 })
		.toBuffer();

	const limit = PERFORMANCE_BUDGETS[budget];
	if (tile.length > limit) {
		throw new Error(
			`Texture ${sourcePath} trop lourde : ${tile.length} octets pour un budget de ${limit}.`
		);
	}
	return tile;
}

type AuthVariant = { path: string; width: number; contents: Buffer };

async function renderAuthImages(
	root: string,
	branding: Branding
): Promise<{ files: GeneratedFile[]; auth: AuthImages }> {
	const source = await readFile(path.join(root, branding.authSource));
	const variants: AuthVariant[] = [];
	for (const width of AUTH_WIDTHS) {
		const height = Math.round(width * AUTH_RATIO);
		const contents = await sharp(source)
			.resize(width, height, { fit: 'cover', position: 'centre' })
			.webp({ quality: width >= 1200 ? 80 : 78, effort: 6 })
			.toBuffer();
		const budget =
			width <= 640
				? PERFORMANCE_BUDGETS.authMobileImageBytes
				: PERFORMANCE_BUDGETS.authDesktopImageBytes;
		if (contents.length > budget) {
			throw new Error(
				`Photo de connexion ${width}px trop lourde : ${contents.length} octets pour un budget de ${budget}.`
			);
		}
		variants.push({
			path: `/auth/dressing-room-${width}-${sha256(contents).slice(0, 12)}.webp`,
			width,
			contents
		});
	}
	const largest = variants.at(-1) as AuthVariant;
	return {
		files: variants.map((variant) => ({
			path: `static${variant.path}`,
			contents: variant.contents
		})),
		auth: {
			src: largest.path,
			srcset: variants.map((variant) => `${variant.path} ${variant.width}w`).join(', '),
			width: largest.width,
			height: Math.round(largest.width * AUTH_RATIO)
		}
	};
}

