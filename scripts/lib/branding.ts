function cachePrefix(branding: Branding): string {
	const slug = branding.shortName
		.toLowerCase()
		.normalize('NFD')
		.replace(/[\u0300-\u036f]/g, '')
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-+|-+$/g, '');
	return slug || 'app';
}

export async function buildCriticalCss(root: string): Promise<string> {
	const tokens = await readFile(path.join(root, 'src/lib/ui/tokens.css'), 'utf8');
	const start = tokens.indexOf('@theme {');
	const end = tokens.indexOf('\n}', start);
	if (start < 0 || end < 0) {
		throw new Error('Le bloc @theme de tokens.css est introuvable.');
	}
	const variables = `:root ${tokens.slice(start + '@theme '.length, end + 2)}`;
	const critical = await readFile(path.join(root, 'src/lib/ui/critical.css'), 'utf8');
	return `${variables}\n${critical}`;
}

